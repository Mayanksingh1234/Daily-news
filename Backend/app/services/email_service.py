import os
import smtplib
from email.message import EmailMessage
from dotenv import load_dotenv

load_dotenv()


class EmailService:
    def __init__(self):
        self.email = os.getenv("GMAIL_EMAIL")
        self.app_password = os.getenv("GMAIL_APP_PASSWORD")

        if not self.email:
            raise RuntimeError("GMAIL_EMAIL is not configured")

        if not self.app_password:
            raise RuntimeError("GMAIL_APP_PASSWORD is not configured")

    def send_episode_email(
        self,
        to_email: str,
        title: str,
        audio_url: str,
    ):
        message = EmailMessage()

        message["Subject"] = f"Your Daily Podcast: {title}"
        message["From"] = self.email
        message["To"] = to_email

        message.set_content(
            f"""
            Your Daily Podcast is Ready

            Your scheduled research briefing "{title}" has been generated successfully.

            Listen to your episode here:

            {audio_url}

            This email was automatically generated by Daily Podcast Agent.
            """
        )

        with smtplib.SMTP_SSL(
            "smtp.gmail.com",
            465,
            timeout=30,
        ) as server:
            server.login(
                self.email,
                self.app_password,
            )

            server.send_message(message)

        print(f"[EMAIL] Episode email sent to {to_email}")

        return {
            "status": "sent",
            "to": to_email,
        }